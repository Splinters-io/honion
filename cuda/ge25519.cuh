// Group arithmetic on the Ed25519 curve, and the incremental walk that makes
// vanity search cheap.
//
// ## The idea
//
// A naive search generates a random secret scalar, multiplies the base point by
// it, and checks the resulting address. Scalar multiplication costs roughly 250
// point operations, which caps throughput far below what the hardware can do.
//
// Ed25519 clamping clears the low three bits of every secret scalar, so every
// valid scalar is a multiple of 8. Therefore, starting from any valid scalar a
// and its public point A = a*B, the sequence
//
//     a_k = a + 8k          A_k = A_{k-1} + 8B
//
// visits valid scalars using a single point *addition* per candidate. Since 8B
// is a compile-time constant available in precomputed affine form, that
// addition is a "mixed" addition costing eight field multiplications rather
// than the ~2000 a scalar multiplication would need.
//
// The host knows a and receives k, so it can reconstruct the secret as a + 8k
// without the device ever holding secret material. See
// `docs/05-security-model.md`.
//
// ## Coordinates
//
// Points are kept in extended coordinates (X:Y:Z:T) with x = X/Z, y = Y/Z and
// XY = ZT, which makes addition inversion-free. Recovering the affine y needed
// for an address costs one modular inversion — far more than the addition
// itself — so inversions are batched; see `fe_batch_invert_step` and the
// comment on Montgomery's trick in search.cu.

#pragma once

#if FE_RADIX32
#include "fe25519_u32.cuh"
#else
#include "fe25519.cuh"
#endif

// Extended coordinates: x = X/Z, y = Y/Z, T = XY/Z.
struct ge_p3 {
    fe X, Y, Z, T;
};

// The output of a mixed addition: x = X/Z, y = Y/T. Cheaper to produce than a
// p3 and converted only when the next addition needs it.
struct ge_p1p1 {
    fe X, Y, Z, T;
};

// An affine point in "niels" form, precomputed for use as the second operand of
// a mixed addition.
struct ge_precomp {
    fe yplusx, yminusx, xy2d;
};


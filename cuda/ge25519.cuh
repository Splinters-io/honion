// r = p + q, where q is an affine point in niels form.
//
// This is the "madd" formula for extended twisted Edwards coordinates with
// a = -1. Eight field multiplications in total: four here and four in
// ge_p1p1_to_p3.
__device__ __forceinline__ void ge_madd(ge_p1p1 *r, const ge_p3 *p,
                                        const ge_precomp *q) {
    fe t0;
    fe_add(r->X, p->Y, p->X);        // A = Y1 + X1
    fe_sub(r->Y, p->Y, p->X);        // B = Y1 - X1
    fe_mul(r->Z, r->X, q->yplusx);   // C = A * (y2 + x2)
    fe_mul(r->Y, r->Y, q->yminusx);  // D = B * (y2 - x2)
    fe_mul(r->T, q->xy2d, p->T);     // E = T1 * 2*d*x2*y2
    fe_add(t0, p->Z, p->Z);          // F = 2*Z1
    fe_sub(r->X, r->Z, r->Y);        // X3 = C - D
    fe_add(r->Y, r->Z, r->Y);        // Y3 = C + D
    fe_add(r->Z, t0, r->T);          // Z3 = F + E
    fe_sub(r->T, t0, r->T);          // T3 = F - E
}

// Convert a p1p1 back to extended coordinates. Four multiplications.
__device__ __forceinline__ void ge_p1p1_to_p3(ge_p3 *r, const ge_p1p1 *p) {
    fe_mul(r->X, p->X, p->T);
    fe_mul(r->Y, p->Y, p->Z);
    fe_mul(r->Z, p->Z, p->T);
    fe_mul(r->T, p->X, p->Y);
}

// The niels form of 8*B, assembled from the generated constants above.
__device__ __forceinline__ void ge_precomp_8b(ge_precomp *q) {
    fe_copy(q->yplusx, ge_8b_yplusx);
    fe_copy(q->yminusx, ge_8b_yminusx);
    fe_copy(q->xy2d, ge_8b_xy2d);
}

// p += 8*B, in place.
__device__ __forceinline__ void ge_add_8b(ge_p3 *p) {
    ge_precomp q;
    ge_precomp_8b(&q);
    ge_p1p1 t;
    ge_madd(&t, p, &q);
    ge_p1p1_to_p3(p, &t);
}

// Compress a point to the 32-byte encoding an Ed25519 public key uses: the
// affine y, little-endian, with the low bit of the affine x in bit 255.
//
// Costs a modular inversion, so the search kernel does *not* call this per
// candidate; it batches the inversions instead. Provided for setup, tests, and
// the rare reporting path.
__device__ __noinline__ void ge_p3_tobytes(u8 *s, const ge_p3 *p) {
    fe recip, x, y;
    fe_invert(recip, p->Z);
    fe_mul(x, p->X, recip);
    fe_mul(y, p->Y, recip);
    fe_tobytes(s, y);
    s[31] ^= (u8)(fe_isnegative(x) << 7);
}

// Decompress a 32-byte public key into extended coordinates.
//
// Returns 1 on success, 0 when the encoding does not name a curve point. The
// caller must check: a search thread whose starting point failed to decompress
// would otherwise walk a sequence of meaningless values at full speed and
// report nothing, which is indistinguishable from bad luck. Failure here means
// the host sent something that is not a public key, so it is a bug, and the
// kernel reports it rather than absorbing it.
//
// The square root is computed as (u/v)^((p+3)/8) via the identity
// x = u v^3 (u v^7)^((p-5)/8), which needs one exponentiation rather than two.
// When that root is off by a factor of sqrt(-1) — which happens for half of all
// inputs — it is corrected by multiplying it back in.
__device__ __noinline__ u32 ge_frombytes(ge_p3 *h, const u8 *s) {
    fe u, v, v3, vxx, check;

    fe_frombytes(h->Y, s);
    fe_1(h->Z);
    fe_sq(u, h->Y);
    fe_mul(v, u, fe_d);
    fe_sub(u, u, h->Z);   // u = y^2 - 1
    fe_add(v, v, h->Z);   // v = d*y^2 + 1

    fe_sq(v3, v);
    fe_mul(v3, v3, v);    // v^3
    fe_sq(h->X, v3);
    fe_mul(h->X, h->X, v);
    fe_mul(h->X, h->X, u); // u * v^7

    fe_pow22523(h->X, h->X);
    fe_mul(h->X, h->X, v3);
    fe_mul(h->X, h->X, u); // x = u * v^3 * (u * v^7)^((p-5)/8)

    fe_sq(vxx, h->X);
    fe_mul(vxx, vxx, v);
    fe_sub(check, vxx, u); // v*x^2 - u
    if (fe_isnonzero(check)) {
        fe_add(check, vxx, u); // v*x^2 + u
        if (fe_isnonzero(check)) {
            return 0; // u/v is not a square: not a point
        }
        fe_mul(h->X, h->X, fe_sqrtm1);
    }

    // Match the sign bit the encoding asked for.
    if (fe_isnegative(h->X) != (u32)(s[31] >> 7)) {
        fe_neg(h->X, h->X);
    }
    fe_mul(h->T, h->X, h->Y);
    return 1;
}

// Whether a point satisfies the curve equation -x^2 + y^2 = 1 + d*x^2*y^2.
//
// Used by the tests and by the kernel's optional self-check. A point that
// drifts off the curve is the signature of a field-arithmetic bug or a memory
// fault, and is worth detecting explicitly rather than inferring from a search
// that mysteriously never succeeds.
__device__ __noinline__ u32 ge_p3_is_on_curve(const ge_p3 *p) {
    fe recip, x, y, x2, y2, lhs, rhs, t;
    fe_invert(recip, p->Z);
    fe_mul(x, p->X, recip);
    fe_mul(y, p->Y, recip);
    fe_sq(x2, x);
    fe_sq(y2, y);
    fe_sub(lhs, y2, x2);          // y^2 - x^2
    fe_mul(t, x2, y2);
    fe_mul(rhs, t, fe_d);
    fe_1(t);
    fe_add(rhs, rhs, t);          // 1 + d*x^2*y^2
    fe_sub(t, lhs, rhs);
    return fe_isnonzero(t) ? 0u : 1u;
}

// ---------------------------------------------------------------------------
// The dual addition law
// ---------------------------------------------------------------------------
//
// For a twisted Edwards curve with a = -1, the y coordinate of a sum can be
// written without reference to the curve constant d, and without ever forming
// projective coordinates for the result:
//
//     y(P + Q) = (x1*y1 - x2*y2) / (x1*y2 - y1*x2)
//     y(P - Q) = (x1*y1 + x2*y2) / (x1*y2 + y1*x2)
//
// (Verified against the standard addition law in `cuda/verify_dual_law.py`.)
//
// Two properties make this the right formula for a vanity search:
//
//   * Only y is produced, which is all an address needs — the x coordinate
//     costs nothing because it is never computed.
//   * The two results share the products `x1*y2` and `y1*x2`, differing only in
//     an addition versus a subtraction. Two candidates for the price of two
//     multiplications.
//
// The results are fractions. Since a batch inversion is required anyway, the
// numerator and denominator are carried separately and the division happens
// once for the whole batch — so the "division" in the formulas above is free.
//
// See docs/01-ed25519-vanity-search.md.

// An affine point, with its x*y product precomputed.
//
// `xy` is what makes the dual law cheap: it is the term that distinguishes
// P+Q from P-Q, and precomputing it for the fixed offsets means the moving
// point contributes only two multiplications per pair of candidates.
struct ge_affine {
    fe x, y, xy;
};

// Numerator and denominator of a candidate's y coordinate.
struct ge_yfrac {
    fe num, den;
};

// The y coordinates of `base + off` and `base - off`, as unreduced fractions.
//
// Costs exactly two multiplications for both results.
__device__ __forceinline__ void ge_dual_pair(ge_yfrac *plus, ge_yfrac *minus,
                                             const ge_affine *base,
                                             const fe off_x, const fe off_y,
                                             const fe off_xy) {
    fe x1y2, y1x2;
    fe_mul(x1y2, base->x, off_y);   // x1 * y2
    fe_mul(y1x2, base->y, off_x);   // y1 * x2

    fe_sub(plus->num, base->xy, off_xy);   // x1*y1 - x2*y2
    fe_sub(plus->den, x1y2, y1x2);         // x1*y2 - y1*x2
    fe_add(minus->num, base->xy, off_xy);  // x1*y1 + x2*y2
    fe_add(minus->den, x1y2, y1x2);        // x1*y2 + y1*x2
}

// Affine form of an extended-coordinate point, given 1/Z.
__device__ __forceinline__ void ge_p3_to_affine(ge_affine *a, const ge_p3 *p,
                                                const fe zinv) {
    fe_mul(a->x, p->X, zinv);
    fe_mul(a->y, p->Y, zinv);
    fe_mul(a->xy, a->x, a->y);
}

// 8*B as an extended-coordinate point, from the generated affine constants.
__device__ __forceinline__ void ge_p3_8b(ge_p3 *p) {
    fe_copy(p->X, ge_8b_x);
    fe_copy(p->Y, ge_8b_y);
    fe_1(p->Z);
    fe_mul(p->T, ge_8b_x, ge_8b_y);
}

// Convert an affine point to niels form, so it can be the second operand of a
// mixed addition.
__device__ __forceinline__ void ge_affine_to_precomp(ge_precomp *q, const fe x,
                                                     const fe y) {
    fe t;
    fe_add(q->yplusx, y, x);
    fe_sub(q->yminusx, y, x);
    fe_mul(t, x, y);
    fe_mul(t, t, fe_d);
    fe_add(q->xy2d, t, t);   // 2*d*x*y
}
